def is_known(code):
    """Есть ли такой прибор в списке."""
    return code in _BY_CODE


def title_for(code, fallback=None):
    """Название прибора по его code.

    Неизвестный code возвращается как есть: в заявке может оказаться значение,
    которого в списке уже нет (например, прибор убрали из услуг, а заявка
    пришла вчера). Тогда лучше показать то, что прислали, чем пустоту.
    """
    service = _BY_CODE.get(code)
    if service:
        return service["title"]
    if fallback is not None:
        return fallback
    return code
