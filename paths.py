"""Пути проекта.

Держим в одном месте, чтобы рабочие данные не зависели от того, из какой
папки запустили скрипт. Раньше было open("requests.csv", "a") — файл
создавался в текущей директории, и при запуске из другой папки данные
терялись в неизвестном месте.
"""

from pathlib import Path

# Корень проекта — папка, где лежит этот файл.
ROOT_DIR = Path(__file__).resolve().parent

# Папка рабочих данных: база посещений, заявки с сайта, заявки из Telegram.
DATA_DIR = ROOT_DIR / "data"


def data_file(name):
    """Возвращает путь к файлу в data/ и создаёт папку, если её ещё нет.

    Вызывать на каждый чих не нужно: проверка дешёвая, mkdir идемпотентный.
    """
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    return DATA_DIR / name
